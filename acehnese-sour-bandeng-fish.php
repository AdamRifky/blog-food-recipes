                    <h3 class="text-lg font-semibold pb-2">For the Fish:</h3>
                    <ul class="list-disc pl-5">
                        <li>1 whole bandeng fish (approximately 500 g)</li>
                        <li>1 lime (juice)</li>
                        <li>Water, as needed</li>
                        <li>15 pieces of belimbing wuluh (starfruit)</li>
                        <li>3 kaffir lime leaves</li>
                        <li>2 stalks of curry leaves</li>
                        <li>10 whole bird's eye chilies</li>
                        <li>Salt, to taste</li>
                        <li>Chicken broth powder, to taste</li>
                        <li>1 teaspoon sugar</li>
                    </ul>
                    <h3 class="text-lg font-semibold pt-4 pb-2">For the Spice Paste:</h3>
                    <ul class="list-disc pl-5">
                        <li>5 cloves of garlic</li>
                        <li>4 large red chilies</li>
                        <li>1 piece of turmeric (about 1 inch)</li>
                        <li>1 teaspoon coriander powder</li>
                        <li>1/2 teaspoon ground pepper</li>
                    </ul>
                </div>

                <!--Notes-->
                <div class="basis-1/2 p-5">
                    <button type="button" class="text-gray-900 bg-white border border-black hover:bg-gray-100 font-medium text-sm px-10 py-2 mb-2 cursor-default">NOTES</button>
                    <ul class="list-disc pl-5">
                        <li>If you prefer a milder dish, you can reduce the amount of bird's eye chilies or remove the seeds from the red chilies.</li>
                        <li>Using fresh bandeng fish will enhance the flavor of the dish. If bandeng is not available, other white fish can be substituted.</li>
                    </ul>
                </div>
