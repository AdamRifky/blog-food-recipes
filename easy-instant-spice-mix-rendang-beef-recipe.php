          <h3 class="text-lg font-semibold pb-2">Main Ingredients:</h3>
          <ul class="list-disc pl-5">
            <li>500 g beef, thinly sliced</li>
            <li>Water</li>
            <li>3 kaffir lime leaves</li>
            <li>1 bay leaf</li>
            <li>1 pack of instant coconut milk (like Kara)</li>
            <li>1 packet of rendang instant spice mix (such as Bamboe)</li>
            <li>2 tbsp sweet soy sauce</li>
            <li>Sugar and MSG to taste</li>
          </ul>
          <h3 class="text-lg font-semibold pt-4 pb-2">Spice Paste:</h3>
          <ul class="list-disc pl-5">
            <li>10 shallots</li>
            <li>7 cloves garlic</li>
          </ul>
        </div>

        <!--Notes-->
        <div class="basis-1/2 p-5">
          <button type="button" class="text-gray-900 bg-white border border-black hover:bg-gray-100 font-medium text-sm px-10 py-2 mb-2 cursor-default">NOTES</button>
          <ul class="list-disc pl-5">
            <li>Use fresh beef for the best flavor and texture.</li>
            <li>Adjust the amount of water to control the thickness of the sauce.</li>
            <li>Add the kaffir lime leaves and bay leaf for an authentic aroma.</li>
            <li>Cook on low heat for a longer time to ensure the beef becomes tender.</li>
            <li>Stir regularly to prevent the sauce from sticking to the pan.</li>
            <li>If you prefer a creamier texture, add more coconut milk.</li>
            <li>Sweet soy sauce adds a hint of sweetness; adjust according to preference.</li>
            <li>Balance MSG and sugar carefully to enhance flavor without overpowering it.</li>
          </ul>
        </div>
