                    <h3 class="text-lg font-semibold pt-4 pb-2">For the Spice Paste:</h3>
                    <ul class="list-disc pl-5">
                        <li>20 shallots</li>
                        <li>10 cloves of garlic</li>
                        <li>2 inches turmeric</li>
                        <li>1 tablespoon coriander powder</li>
                        <li>1/2 teaspoon cumin</li>
                        <li>10 bird's eye chilies</li>
                        <li>5 curly red chilies</li>
                        <li>1 thumb-sized galangal</li>
                    </ul>
                    <h3 class="text-lg font-semibold pt-4 pb-2">For Additional Seasoning:</h3>
                    <ul class="list-disc pl-5">
                        <li>2 stalks lemongrass</li>
                        <li>10 kaffir lime leaves</li>
                        <li>1 turmeric leaf</li>
                        <li>10 cm cinnamon stick</li>
                        <li>3 cloves</li>
                        <li>2 bay leaves</li>
                    </ul>
                    <h3 class="text-lg font-semibold pt-4 pb-2">For Garnish:</h3>
                    <ul class="list-disc pl-5">
                        <li>Fried shallots, to taste</li>
                    </ul>
                </div>

